const assert=require('node:assert/strict');
const D=require('./date-picker');
assert.equal(D.parse('2.10.2026'),'2026-10-02');
assert.equal(D.parse('02.10.2026'),'2026-10-02');
assert.equal(D.parse('2026-10-02'),'2026-10-02');
assert.equal(D.format('2026-10-02'),'02.10.2026');
for(const value of ['','31.04.2026','29.02.2026','2026-02-29','32.10.2026','02.13.2026','02.10.26','text'])assert.equal(D.parse(value),null,value);
assert.equal(D.parse('29.02.2024'),'2024-02-29');
assert.equal(D.addDays('2025-12-31',1),'2026-01-01');
assert.equal(D.addDays('2026-01-01',-1),'2025-12-31');
assert.equal(D.addMonths('2024-01-31',1),'2024-02-29');
assert.equal(D.addMonths('2026-01-31',1),'2026-02-28');
assert.equal(D.addMonths('2024-02-29',12),'2025-02-28');
assert.equal(D.addMonths('2026-01-31',-1),'2025-12-31');
const october=D.monthCells('2026-10','2026-10-02','2026-10-28');
assert.equal(october.length,42);assert.equal(october[0].date,'2026-09-28');assert.equal(october.at(-1).date,'2026-11-08');
assert.equal(new Set(october.map(c=>c.date)).size,42);
assert.equal(october.filter(c=>!c.disabled).length,27);
assert.equal(october.find(c=>c.date==='2026-10-01').disabled,true);
assert.equal(october.find(c=>c.date==='2026-10-02').disabled,false);
assert.equal(october.find(c=>c.date==='2026-10-28').disabled,false);
assert.equal(october.find(c=>c.date==='2026-10-29').disabled,true);
assert(october.filter(c=>c.outside).every(c=>c.disabled));
const leap=D.monthCells('2024-02');assert.equal(leap.filter(c=>!c.outside).length,29);
const sixRows=D.monthCells('2026-03');assert.equal(sixRows[0].date,'2026-02-23');assert.equal(sixRows.at(-1).date,'2026-04-05');
assert.equal(D.allowed('2026-10-02','2026-10-02','2026-10-02'),true);
assert.equal(D.allowed('2026-10-03','2026-10-02','2026-10-02'),false);
console.log('PASS date picker: Russian manual dates, invalid/leap dates, Monday-first six-week grids, month/year transitions, inclusive date bounds');
